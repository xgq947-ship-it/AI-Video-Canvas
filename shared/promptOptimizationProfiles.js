export function formatOptimizedPrompt(text, profile) {
  let cleaned = String(text || '')
    .trim()
    .replace(/^```(?:text|plaintext)?\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim()
    .replace(/^["']|["']$/g, '')
    .trim();

  if (!profile?.aspectRatio) return cleaned;

  cleaned = cleaned
    .replace(/^输出图片尺寸比例\s*[：:]\s*[^\n]+\n*/i, '')
    .trim();
  return `输出图片尺寸比例：${profile.aspectRatio}\n\n${cleaned}`;
}
